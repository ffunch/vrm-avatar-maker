"""Generate futuristic visors as editor items (our own geometry and texture, so no license questions).

A visor is a curved band in front of the eyes, sized from the MakeHuman base mesh: centered on the
eyes, wrapping toward the temples. It becomes a normal .mhclo item: each vertex is tied to its
nearest head vertex that the face shapes don't move (so the visor stays put when the avatar talks),
with the offset scaled by the head's width, height and depth like any MakeHuman item.

Stdlib only. Writes assets/parts/<id>/ (obj, mhclo, mhmat, png texture, thumb).
Usage: python3 pipeline/make_visor.py
"""

import gzip
import json
import math
import os
import struct
import zlib

HOME = os.path.expanduser("~")
SYSTEM = os.path.join(HOME, "Library/Application Support/Blender/5.2/extensions/blender_org/mpfb/data")
USER = os.path.join(HOME, "Library/Application Support/Blender/5.2/extensions/.user/blender_org/mpfb/data")
REPO = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

VISORS = {
    # id: (half-angle of the wrap in degrees, bottom and top relative to eye height in dm, colors)
    "visor_band": (78, -0.17, 0.2, ((20, 24, 32), (60, 220, 255))),   # tall dark visor, cyan edge
    "visor_slit": (82, -0.07, 0.09, ((30, 10, 40), (255, 80, 200))),  # narrow band, magenta glow
}


def read_base():
    pos = []
    for line in open(os.path.join(SYSTEM, "3dobjs/base.obj"), errors="replace"):
        if line.startswith("v "):
            pos.append([float(x) for x in line.split()[1:4]])
    return pos


def png(path, width, height, pixel):
    rows = b"".join(b"\0" + bytes(c for x in range(width) for c in pixel(x, y)) for y in range(height))
    chunk = lambda kind, data: struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))
    with open(path, "wb") as handle:
        handle.write(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0))
                     + chunk(b"IDAT", zlib.compress(rows, 9)) + chunk(b"IEND", b""))


B = read_base()
groups = json.load(open(os.path.join(SYSTEM, "mesh_metadata/basemesh_vertex_groups.json")))
members = lambda name: [i for a, b in groups[name] for i in range(a, b + 1)]
mean = lambda idx: [sum(B[i][k] for i in idx) / len(idx) for k in range(3)]
left, right = mean(members("helper-l-eye")), mean(members("helper-r-eye"))
eyes = [(a + b) / 2 for a, b in zip(left, right)]
body = set(members("body"))

# Head vertices the face shapes leave alone: candidates for anchoring.
moving = set()
for folder in ("visemes", "faceunits"):
    for name in os.listdir(os.path.join(USER, "targets", folder)):
        for line in open(os.path.join(USER, "targets", folder, name), errors="replace"):
            parts = line.split()
            if len(parts) == 4 and max(abs(float(v)) for v in parts[1:]) > 0.002:
                moving.add(int(parts[0]))
anchors = [i for i in body if B[i][1] > eyes[1] - 0.8 and abs(B[i][0]) < 1.0 and i not in moving]

# Scale references like a MakeHuman glasses item: head width, height and depth on the base mesh.
def extreme(axis, sign, pool):
    return max(pool, key=lambda i: sign * B[i][axis])
head = [i for i in body if B[i][1] > eyes[1] - 1.2]
scale = {"x": (extreme(0, 1, head), extreme(0, -1, head)), "y": (extreme(1, 1, head), extreme(1, -1, head)),
         "z": (extreme(2, 1, head), extreme(2, -1, head))}

front = max(B[i][2] for i in body if abs(B[i][1] - eyes[1]) < 0.3 and abs(B[i][0]) < 0.6)  # brow/nose front
for vid, (half_angle, bottom, top, (dark, glow)) in VISORS.items():
    out = os.path.join(REPO, "assets", "parts", vid)
    os.makedirs(out, exist_ok=True)
    radius = 0.95
    cz = front + 0.12 - radius
    cols, rows = 28, 5
    verts, uvs, faces = [], [], []
    for r in range(rows + 1):
        y = eyes[1] + bottom + (top - bottom) * r / rows
        for c in range(cols + 1):
            a = math.radians(-half_angle + 2 * half_angle * c / cols)
            rr = radius * (1 + 0.04 * (r / rows - 0.5) ** 2)  # slight vertical curve
            verts.append((rr * math.sin(a), y, cz + rr * math.cos(a)))
            uvs.append((c / cols, r / rows))
    for r in range(rows):
        for c in range(cols):
            i = r * (cols + 1) + c
            faces.append((i, i + 1, i + cols + 2, i + cols + 1))
    with open(os.path.join(out, vid + ".obj"), "w") as handle:
        handle.write("# Generated by pipeline/make_visor.py (AvatarEditor, CC0)\n")
        handle.writelines(f"v {x:.5f} {y:.5f} {z:.5f}\n" for x, y, z in verts)
        handle.writelines(f"vt {u:.5f} {v:.5f}\n" for u, v in uvs)
        handle.writelines("f " + " ".join(f"{i + 1}/{i + 1}" for i in face) + "\n" for face in faces)
    with open(os.path.join(out, vid + ".mhclo"), "w") as handle:
        handle.write(f"# Generated by pipeline/make_visor.py (AvatarEditor, CC0)\nname {vid}\nobj_file {vid}.obj\n")
        for axis, (a, b) in scale.items():
            k = "xyz".index(axis)
            handle.write(f"{axis}_scale {a} {b} {abs(B[a][k] - B[b][k]):.4f}\n")
        handle.write(f"z_depth 55\nmaterial {vid}.mhmat\nverts 0\n")
        for p in verts:
            n = min(anchors, key=lambda i: (B[i][0] - p[0]) ** 2 + (B[i][1] - p[1]) ** 2 + (B[i][2] - p[2]) ** 2)
            o = [p[k] - B[n][k] for k in range(3)]
            handle.write(f"{n} {n} {n} 1.0 0.0 0.0 {o[0]:.5f} {o[1]:.5f} {o[2]:.5f}\n")
    with open(os.path.join(out, vid + ".mhmat"), "w") as handle:
        handle.write(f"name {vid}\ndiffuseTexture {vid}.png\n")

    def pixel(x, y, w=128, h=32, dark=dark, glow=glow):
        edge = min(y, h - 1 - y) / (h / 2)                      # 0 at top/bottom edge, 1 in the middle
        g = max(0.0, 1 - edge * 5) + 0.25 * max(0.0, 1 - abs(y - h * 0.42) / 2)  # glowing rim, thin center line
        shine = 0.25 * max(0.0, 1 - abs(x - w * 0.3) / (w * 0.08)) * (1 - edge * 0.3)  # a highlight streak
        return tuple(min(255, int(d * (1 - g) + gl * g + 255 * shine)) for d, gl in zip(dark, glow))
    png(os.path.join(out, vid + ".png"), 128, 32, pixel)
    png(os.path.join(out, vid + ".thumb"), 128, 128, lambda x, y, p=pixel: (30, 30, 30) if not 48 <= y < 80 else p(x, (y - 48)))
    print(vid, len(verts), "vertices,", 2 * len(faces), "triangles ->", out)
